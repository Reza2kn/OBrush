#!/usr/bin/env python3
"""Build/check a complete current-status crosswalk for the pinned 317-ID inventory.

The frozen table describes the 0.1.14 gap. This report never infers present
implementation or parity from an old label. A scoped evidence link means only
that a specific later report exists; all active acceptance gates remain open.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "docs/SCULPTGL_PARITY.md"
OVERRIDES = ROOT / "docs/evidence/sculptgl-current-overrides.json"
OUTPUT = ROOT / "docs/SCULPTGL_CURRENT_LEDGER.md"
PIN = "8e45dafc0f7906e5238dfffc1a2df742bd25f29d"
EXPECTED = 317
INACTIVE = {
    "SGL-EXTERNAL-SCULPTEO",
    "SGL-EXTERNAL-MATERIALISE",
    "SGL-INACTIVE-TORUS-BUILDER",
    "SGL-SOURCE-ASCII-PLY-EXPORT",
    "SGL-SOURCE-ASCII-STL-EXPORT",
}
ABSENT = {"SGL-ABSENT-REPLAY", "SGL-ABSENT-AUTOSAVE"}
INERT = {"SGL-TRANSFORM-VIEW-ROTATE"}
ROW = re.compile(r"^\| (SGL-[A-Z0-9_-]+) \|")


def inventory() -> list[tuple[str, str]]:
    rows = []
    seen = set()
    for line in SOURCE.read_text().splitlines():
        match = ROW.match(line)
        if not match:
            continue
        cells = [cell.strip() for cell in line.split("|")[1:-1]]
        if len(cells) != 4:
            raise ValueError(f"Inventory row has {len(cells)} columns: {match.group(1)}")
        ident = match.group(1)
        if ident in seen:
            raise ValueError(f"Duplicate inventory ID: {ident}")
        if PIN not in cells[1]:
            raise ValueError(f"Missing pinned source pointer: {ident}")
        if not cells[3]:
            raise ValueError(f"Missing acceptance gate: {ident}")
        seen.add(ident)
        rows.append((ident, cells[3]))
    if len(rows) != EXPECTED:
        raise ValueError(f"Expected {EXPECTED} pinned IDs, found {len(rows)}")
    for name, group in (("inactive", INACTIVE), ("absent", ABSENT), ("inert", INERT)):
        missing = group - seen
        if missing:
            raise ValueError(f"Unknown {name} ID(s): {sorted(missing)}")
    return rows


def render() -> str:
    rows = inventory()
    overrides = json.loads(OVERRIDES.read_text())
    ids = {ident for ident, _ in rows}
    if unknown := set(overrides) - ids:
        raise ValueError(f"Evidence names unknown ID(s): {sorted(unknown)}")
    if overlap := (INACTIVE & ABSENT) | (INACTIVE & INERT) | (ABSENT & INERT):
        raise ValueError(f"Conflicting reference scope: {sorted(overlap)}")
    for ident, paths in overrides.items():
        if ident in INACTIVE | ABSENT | INERT:
            raise ValueError(f"Scoped active evidence applied to non-active ID: {ident}")
        if not isinstance(paths, list) or not paths:
            raise ValueError(f"Empty evidence list: {ident}")
        for path in paths:
            if not isinstance(path, str) or not (ROOT / "docs" / path).is_file():
                raise ValueError(f"Missing evidence file for {ident}: {path}")
    active = EXPECTED - len(INACTIVE | ABSENT | INERT)
    lines = [
        "# Current SculptGL inventory crosswalk",
        "",
        "Generated by `python3 scripts/audit-sculptgl-inventory.py`. "
        "The [frozen inventory](SCULPTGL_PARITY.md) defines the exact pinned "
        "reference workflow and acceptance gate for each ID. This crosswalk "
        "does not turn an old 0.1.14 gap label into a current product claim.",
        "",
        f"**{EXPECTED} unique pinned IDs:** {active} active workflows, "
        f"{len(INACTIVE)} source-only/inactive, {len(INERT)} drawn but inert, "
        f"{len(ABSENT)} absent from the pinned baseline. "
        f"{len(overrides)} active IDs have later scoped evidence linked below. "
        "Every active ID remains parity-open; unlinked means current row-level "
        "evidence has not been reconciled, not that OBrush lacks the feature.",
        "",
        "A scoped report may cover one fixture or option and never closes its "
        "full acceptance gate by itself. The paired million-vertex [C226]"
        "(SCULPTGL_MILLION_PAIRED_C226.md) and later [C228]"
        "(SCULPTGL_CERTIFIED_RENDER_HANDOFF_C228.md)/[C229]"
        "(SCULPTGL_RETAINED_TOPOLOGY_WALK_C229.md) results still fail all "
        "four responsiveness gates. [C253]"
        "(SOURCE_ORDINARY_WORKER_SPIKE_C253.md) measures raw browser Worker "
        "transport and records why an ordinary held-pointer candidate has "
        "not yet been integrated; it changes none of those failures.",
        "",
        "The [C263 combined receipt](SCULPTGL_COMBINED_C263.md) validates "
        "scoped Source Move and viewport Shift-click behavior, reconciles "
        "Continuous/culling evidence, and records a 100k renderer diagnostic. "
        "Its Worker seams remain non-publishing: there is still no ordinary "
        "Worker sculpt or passing million-vertex held-pointer result, so all "
        "full responsiveness gates remain open.",
        "",
        "| ID | Pinned reference scope | Current row-level evidence | Parity gate |",
        "| --- | --- | --- | --- |",
    ]
    for ident, _gate in rows:
        if ident in INACTIVE:
            scope = "Source-only / inactive UI"
            evidence = "Pinned source boundary only"
            gate = "Reopen if exposed in pinned runtime"
        elif ident in ABSENT:
            scope = "Absent from pinned baseline"
            evidence = "Pinned absence audit only"
            gate = "Not a SculptGL requirement"
        elif ident in INERT:
            scope = "Drawn but inert in pinned runtime"
            evidence = "[C194](SCULPTGL_GIZMO_RUNTIME_C194.md)"
            gate = "Visual/inert behavior open"
        else:
            scope = "Active"
            paths = overrides.get(ident)
            evidence = (
                ", ".join(f"[{Path(path).stem}]({path})" for path in paths)
                if paths
                else "Unreconciled"
            )
            gate = "Open"
        lines.append(f"| {ident} | {scope} | {evidence} | {gate} |")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != expected:
            raise SystemExit("Current SculptGL ledger is missing or stale; regenerate it")
        print(f"Checked {EXPECTED} unique inventory IDs and current ledger")
    else:
        OUTPUT.write_text(expected)
        print(f"Wrote {OUTPUT} with {EXPECTED} unique inventory IDs")
